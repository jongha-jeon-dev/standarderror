def _snippets() -> dict:
    """Every code block in the post, executed here so the build owns the output.

    The seeds are the ones `compute` uses, so the numbers these blocks print are
    the same numbers the figures are drawn from rather than a second run that
    happens to look similar. `expect` pins the values the prose quotes.
    """
    s = Session()
    out = {}

    out["data"] = s.run(f"""
        import numpy as np

        SEED = {SEED}
        # Six features that raise risk and six that lower it, strongest first.
        W = np.array([0.9, 0.7, 0.6, 0.5, 0.4, 0.3,
                      -0.9, -0.7, -0.6, -0.5, -0.4, -0.3])
        SIGNS = tuple(int(np.sign(w)) for w in W)   # what a domain expert asserts

        def make(n, violate=0.0, seed=0):
            rng = np.random.default_rng(seed)
            X = rng.normal(size=(n, W.size))
            # `violate` bends the first feature's true effect into a U while
            # leaving the other eleven monotone. Centring on E[x**2] = 1 keeps the
            # default rate put, so the knob changes shape and nothing else.
            lin = X @ W + violate * (X[:, 0] ** 2 - 1.0)
            y = (rng.random(n) < 1 / (1 + np.exp(-(lin - 1.2)))).astype(int)
            return X, y

        X, y = make(int(500 / 0.7), seed=SEED + 1)
        print("rows", len(y), " default rate", round(y.mean(), 3))
        print("signs", SIGNS)
    """, expect=["rows 714", "default rate 0.361"])

    out["pom"] = s.run("""
        from sklearn.metrics import brier_score_loss, roc_auc_score
        from sklearn.model_selection import train_test_split
        from xgboost import XGBClassifier

        P = dict(n_estimators=200, max_depth=4, learning_rate=0.08, subsample=0.9,
                 colsample_bytree=0.9, reg_lambda=1.0, random_state=0, n_jobs=4)

        def fit_pair(Xtr, ytr, cst):
            "Same rows, same seed, same hyperparameters. Only the constraint differs."
            return (XGBClassifier(**P).fit(Xtr, ytr),
                    XGBClassifier(monotone_constraints=cst, **P).fit(Xtr, ytr))

        def pom(y, p_free, p_tied, metric="auc"):
            "Positive means the constraint made the model worse, on either metric."
            if metric == "auc":                                # higher is better
                a, b = roc_auc_score(y, p_free), roc_auc_score(y, p_tied)
                return 100 * (a - b) / a
            a, b = brier_score_loss(y, p_free), brier_score_loss(y, p_tied)
            return 100 * (b - a) / a                           # lower is better

        Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.3,
                                              random_state=0, stratify=y)
        free, tied = fit_pair(Xtr, ytr, SIGNS)
        pf = free.predict_proba(Xte)[:, 1]
        pt = tied.predict_proba(Xte)[:, 1]
        print(f"PoM, AUC    {pom(yte, pf, pt):+.2f}%")
        print(f"PoM, Brier  {pom(yte, pf, pt, 'brier'):+.2f}%")
    """, expect=["PoM, AUC    -3.03%", "PoM, Brier  -8.14%"])

    out["holds"] = s.run("""
        def wrong_way_steps(model, j, reps=40):
            "Walk feature j across its range with the other eleven pinned."
            grid = np.linspace(-3, 3, 60)
            bad = 0
            for r in range(reps):
                Z = np.tile(Xte[r], (60, 1))
                Z[:, j] = grid
                p = model.predict_proba(Z)[:, 1]
                bad += int((np.diff(p) * SIGNS[j] < -1e-12).sum())
            return bad

        for name, model in (("unconstrained", free), ("constrained  ", tied)):
            print(name, [wrong_way_steps(model, j) for j in (0, 6)])
    """, expect=["constrained   [0, 0]"])

    out["interval"] = s.run(f"""
        def interval(y, pf, pt, metric="auc", reps={BOOT_REPS}, seed=0):
            "Resample test rows, keeping both models paired on every row."
            rng = np.random.default_rng(seed)
            out = np.empty(reps)
            for b in range(reps):
                i = rng.integers(0, y.size, y.size)
                while y[i].min() == y[i].max():     # no AUC without both classes
                    i = rng.integers(0, y.size, y.size)
                out[b] = pom(y[i], pf[i], pt[i], metric)
            return np.quantile(out, [0.025, 0.975])

        for metric, seed in (("auc", SEED + 2), ("brier", SEED + 3)):
            lo, hi = interval(yte, pf, pt, metric, seed=seed)
            print(f"{{metric:5s}} 95% interval  [{{lo:+.2f}}%, {{hi:+.2f}}%]")
    """, expect=["auc   95% interval  [-6.58%, -0.02%]",
                 "brier 95% interval  [-16.72%, +0.97%]"])

    out["flipped"] = s.run("""
        flipped = tuple(-s for s in SIGNS)
        _, wrong = fit_pair(Xtr, ytr, flipped)
        pw = wrong.predict_proba(Xte)[:, 1]
        print(f"correct signs  {pom(yte, pf, pt):+7.2f}%")
        print(f"flipped signs  {pom(yte, pf, pw):+7.2f}%")
    """, expect=["correct signs    -3.03%"])

    return out


def _backwards_fraction(v: float) -> float:
    """Share of a feature's range over which its true effect runs backwards.

    The true contribution of the first feature is 0.9x + v(x^2 - 1), whose slope
    turns negative below x = -0.9 / 2v. The feature is standard normal, so the
    share is just the normal CDF there. This is the only way to say what a
    violation of 0.65 *is* without asking the reader to picture a parabola.
    """
    from scipy.stats import norm
    return float(norm.cdf(-0.9 / (2.0 * v))) if v > 0 else 0.0


