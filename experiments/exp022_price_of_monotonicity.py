"""exp022 - what a monotonicity constraint actually costs, and what decides it.

The paper
---------
Petr Koklev, "What's the Price of Monotonicity? A Multi-Dataset Benchmark of
Monotone-Constrained Gradient Boosting for Credit PD" (arXiv:2512.17945v2, 2025)
defines the Price of Monotonicity as the relative change in a performance metric
between an unconstrained and a monotone-constrained gradient boosting fit, and
measures it on five public credit datasets across three libraries. Its headline is
that the price is small - under 0.2% of AUC on large datasets, 2-3% on small ones
with heavy constraints - and its stated explanation is dataset size and constraint
coverage.

What this post adds
-------------------
The paper's five datasets are five points on a surface. This generates the
surface, on synthetic data whose truth is known, and the shape of it changes the
reading:

1. **The coverage-to-sample-size ratio sets the magnitude and not the sign.** The
   paper's own explanation reproduces exactly: constraining all twelve features on
   500 training rows moves AUC many times more than the same constraint on 20,000.
   But with the truth monotone, every one of those moves is a *gain*. The same
   scaling that the paper reports as costs runs negative here.

2. **The sign is set by whether the constraint is true, and it crosses zero.**
   Bending one feature's true effect into a U shape while leaving its constraint
   in place walks PoM from -0.7% to +10.8%, crossing zero partway. Nothing about
   sample size or coverage changed; only the truth did.

3. **The paper's own wrong-sign diagnostic measures the data, not the
   constraints.** Deliberately flipping every sign gives ~43% here no matter how
   wrong the correct-sign constraints are: it is a measure of how much monotone
   signal the features carry. What moves is the *ratio* of wrong to correct, which
   falls 61-fold to 3.4-fold as violation rises. Across the paper's five datasets
   that ratio ranks against the reported price at Spearman rho = -0.90.

4. **A hypothesis that did not survive, published as one.** The paper's intervals
   come from resampling the test set with the split fixed. If refitting on a new
   split moved PoM more than that interval is wide, the reported significance
   would be understated. It does not: across-split sd is about half the bootstrap
   half-width. The check is reported because it was run, not because it worked.

Numbers in this docstring are restated from the cached run and build() asserts
each of them, so a run whose results have moved fails rather than publishing prose
that no longer matches its own output.

Discipline
----------
Every number here is from synthetic data generated by this file. No real credit
portfolio, no institution, and no company is analysed, named or implied, and
nothing here is a statement about any lender's models. The paper's published
figures are quoted as published and are the only external numbers used.
"""

