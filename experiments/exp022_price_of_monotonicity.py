def _paper_rows(res: dict):
    rows = []
    for name in res["paper_rank"]["names"]:
        d = PAPER[name]
        r = d["wrong"] / d["pom"]
        rows.append([name, f"{d['cov'][0]} of {d['cov'][1]}",
                     f"{d['pom']:.1f}%", f"{d['wrong']:.1f}%",
                     f"{r:.0f}x" if r >= 10 else f"{r:.1f}x"])
    return rows


