def _hero(res: dict):
    h = res["headline_cell"]
    worst = max(r["correct"] for r in res["violation"])
    wrong_lo = min(r["wrong"] for r in res["violation"])
    wrong_hi = max(r["wrong"] for r in res["violation"])

    def held_to_the_rail(panel, m):
        """A rising curve pressed flat against a straight guide."""
        x = np.linspace(0.08, 0.92, 200)
        rail = 0.22 + 0.62 * x
        panel.plot(x, rail, color=m.grid, lw=2.0, ls="--")
        curve = 0.22 + 0.62 * x + 0.06 * np.sin(6.0 * x)
        panel.plot(x, np.maximum.accumulate(curve), color=m.series[0], lw=2.8)
        panel.set_xlim(0, 1); panel.set_ylim(0, 1)

    def the_truth_bends(panel, m):
        """A U-shaped truth with a monotone rail cutting across its left arm."""
        x = np.linspace(0.08, 0.92, 200)
        u = 0.30 + 1.9 * (x - 0.52) ** 2
        panel.plot(x, u, color=m.series[1], lw=2.8)
        panel.plot(x, 0.24 + 0.52 * x, color=m.grid, lw=2.0, ls="--")
        panel.annotate("", xy=(0.20, 0.34), xytext=(0.20, 0.62),
                       arrowprops=dict(arrowstyle="<->", color=m.ink, lw=1.6))
        panel.set_xlim(0, 1); panel.set_ylim(0, 1)

    def forced_the_wrong_way(panel, m):
        """The data rises; the model is held to a line that falls."""
        x = np.linspace(0.10, 0.90, 200)
        panel.plot(x, 0.26 + 0.56 * x, color=m.grid, lw=2.2, ls="--")
        panel.plot(x, 0.74 - 0.48 * x, color=m.series[1], lw=3.0)
        for xx in np.linspace(0.22, 0.78, 5):
            panel.annotate("", xy=(xx, 0.74 - 0.48 * xx),
                           xytext=(xx, 0.26 + 0.56 * xx),
                           arrowprops=dict(arrowstyle="-", color=m.ink,
                                           lw=1.1, alpha=0.55))
        panel.set_xlim(0, 1); panel.set_ylim(0, 1)

    return charts.strip_card(
        headline="A constraint that is true is not a price",
        panels=[
            (held_to_the_rail, f"{h['point_auc']:+.1f}%",
             "true constraint, small n"),
            (the_truth_bends, f"{worst:+.1f}%",
             "once the truth bends"),
            (forced_the_wrong_way, f"{wrong_lo:.0f}-{wrong_hi:.0f}%",
             "signs flipped, any truth"),
        ],
        note=("Synthetic data whose truth is known. A correct constraint pays "
              "rather than costs; the wrong-sign check is nearly constant, "
              "because it reads the features rather than the constraints."),
        footer="The Standard Error", mode="light",
        alt=("A three-panel hand-drawn strip. The first shows a rising curve "
             "pressed against a dashed straight guide line, marked with a "
             "negative percentage. The second shows a U-shaped curve with the "
             "same dashed straight guide cutting across it and a double-headed "
             "arrow measuring the gap, marked with a positive percentage. The "
             "third shows the same dashed guide rising while a heavy line runs "
             "the other way, downward, with thin tension lines drawn between "
             "the two, marked with a percentage range."),
        caption="",
        path=str(IMG / f"a14-hero.{EXT}"))


