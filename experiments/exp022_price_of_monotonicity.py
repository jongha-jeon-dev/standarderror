def _config_key() -> str:
    return json.dumps({"v": 1, "cov_n": COVERAGE_N, "cov_k": COVERAGE_K,
                       "cov_r": COVERAGE_REPEATS, "viol": VIOLATIONS,
                       "viol_n": VIOLATION_N, "viol_r": VIOLATION_REPEATS,
                       "split_n": SPLIT_N, "splits": SPLITS,
                       "boot": SPLIT_BOOT, "b2": BOOT_REPS, "seed": SEED},
                      sort_keys=True)


def _zero_crossing(x, y) -> float | None:
    """Where a sweep first crosses from benefit to cost, linearly interpolated."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    for i in range(1, x.size):
        if y[i - 1] < 0 <= y[i]:
            w = -y[i - 1] / (y[i] - y[i - 1])
            return float(x[i - 1] + w * (x[i] - x[i - 1]))
    return None


def compute(*, force: bool = False, verbose: bool = True) -> dict:
    key = _config_key()
    if CACHE.exists() and not force:
        cached = json.loads(CACHE.read_text())
        if cached.get("key") == key:
            if verbose:
                print(f"exp022: cached ({CACHE})")
            return cached
    t0 = time.time()
    say = print if verbose else (lambda *a, **k: None)
    res = {"key": key}

    # ---- 1. coverage against sample size, truth monotone throughout
    say("coverage sweep")
    cov = mono.coverage_sweep(COVERAGE_N, COVERAGE_K, repeats=COVERAGE_REPEATS,
                              seed=SEED)
    res["coverage"] = {f"{n}|{k}": v for (n, k), v in cov.items()}
    for n in COVERAGE_N:
        say(f"  n={n:<6d} " + "  ".join(
            f"k={k}: {cov[(n, k)]['mean']:+.2f}" for k in COVERAGE_K))

    # ---- 2. the interval on the single strongest cell
    say("\nbootstrap on the strongest cell")
    n_small = COVERAGE_N[0]
    X, y = mono.make_credit_like(int(n_small / 0.7), seed=SEED + 1)
    from sklearn.model_selection import train_test_split
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.3,
                                          random_state=0, stratify=y)
    free, tied = mono.fit_pair(Xtr, ytr, k=12, seed=0)
    pf, pt = free.predict_proba(Xte)[:, 1], tied.predict_proba(Xte)[:, 1]
    res["headline_cell"] = {
        "n_train": int(n_small), "k": 12,
        "auc": mono.paired_bootstrap_pom(yte, pf, pt, metric="auc",
                                         reps=BOOT_REPS,
                                         rng=np.random.default_rng(SEED + 2)),
        "brier": mono.paired_bootstrap_pom(yte, pf, pt, metric="brier",
                                           reps=BOOT_REPS,
                                           rng=np.random.default_rng(SEED + 3)),
        "point_auc": mono.pom(yte, pf, pt, "auc"),
        "point_brier": mono.pom(yte, pf, pt, "brier"),
        "n_test": int(yte.size), "base_rate": float(y.mean())}
    h = res["headline_cell"]
    say(f"  n_train={n_small} k=12  AUC {h['point_auc']:+.2f}% "
        f"[{h['auc']['lo']:+.2f}, {h['auc']['hi']:+.2f}]  "
        f"Brier {h['point_brier']:+.2f}% "
        f"[{h['brier']['lo']:+.2f}, {h['brier']['hi']:+.2f}]")

    # ---- 3. what happens when the constraint stops being true
    say("\nviolation sweep")
    rows = mono.violation_sweep(VIOLATIONS, n_train=VIOLATION_N,
                                repeats=VIOLATION_REPEATS, seed=SEED)
    res["violation"] = rows
    for r in rows:
        r["ratio"] = float(r["wrong"] / r["correct"])
        say(f"  v={r['violation']:.2f}  correct {r['correct']:+6.2f}  "
            f"wrong {r['wrong']:+6.2f}  ratio {r['ratio']:+8.1f}")
    res["crossing"] = _zero_crossing([r["violation"] for r in rows],
                                     [r["correct"] for r in rows])
    say(f"  correct-sign price crosses zero at violation "
        f"{res['crossing']:.2f}" if res["crossing"] else "  no crossing")

    # ---- 4. the paper's five points, ranked
    from scipy.stats import spearmanr
    names = list(PAPER)
    pom_p = [PAPER[k]["pom"] for k in names]
    ratio_p = [PAPER[k]["wrong"] / PAPER[k]["pom"] for k in names]
    rho, p = spearmanr(pom_p, ratio_p)
    res["paper_rank"] = {"names": names, "pom": pom_p,
                         "ratio": [float(r) for r in ratio_p],
                         "rho": float(rho), "p": float(p)}
    say(f"\npaper's five datasets: Spearman rho = {rho:+.2f}, p = {p:.3f}")

    # ---- 5. the hypothesis that did not survive
    say("\nsplit variance against bootstrap width")
    res["split"] = mono.split_variance(SPLIT_N, k=12, splits=SPLITS,
                                       boot=SPLIT_BOOT, seed=SEED)
    s = res["split"]
    say(f"  across-split sd {s['across_split_sd']:.3f}%  vs bootstrap "
        f"half-width {s['bootstrap_half_width']:.3f}%  ratio {s['ratio']:.2f}")

    res["elapsed_s"] = round(time.time() - t0, 1)
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps(res))
    say(f"\nexp022: {res['elapsed_s']}s -> {CACHE}")
    return res


