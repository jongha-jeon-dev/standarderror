"""exp023 - is the saturating LoRA rank a measurement of the task?

The paper
---------
Hananel Hazan, Yanbo Zhang, Benedikt Hartl and Michael Levin, "A Little Rank
Goes a Long Way: Random Scaffolds with LoRA Adapters Are All You Need"
(arXiv:2604.08749v2, 2026) trains low-rank adapters over a backbone that was
never pre-trained - every weight drawn at random and frozen - and recovers
96-100% of fully trained performance across nine benchmarks while optimising
0.5-40% of the parameters. Two of its three mechanistic claims are claims about
*measurement*: that the learned per-layer scalar beta staying positive shows the
frozen backbone is actively exploited, and that the smallest rank at which
performance saturates, r*, estimates the task's intrinsic dimensionality.

Neither claim can be checked on a benchmark. A benchmark does not come with a
known intrinsic dimension, and it does not let you ask what the same run would
have done with no backbone at all. Both can be checked on a task built so that
the answer is known in advance, which is what this experiment does.

What it finds
-------------
1. **The headline reproduces.** On a task whose label depends on the input only
   through a k-dimensional subspace, rank-16 adapters over a frozen random
   backbone match full-weight training while optimising a small fraction of the
   internal parameters.

2. **beta > 0 is not evidence the backbone is used.** The paper's own zero-
   scaffold control already shows this on MNIST, where removing the backbone
   entirely costs nothing at rank 2 and above while beta stays positive. Here the
   same decoupling is measured directly: beta sits near one at every rank while
   the accuracy the backbone is worth falls to nothing.

3. **r* moves with the architecture on a task that never changes.** Holding the
   task literally fixed and varying only the width of the frozen backbone moves
   r* across the grid. No normalisation choice, no change of dataset: the same
   task has several intrinsic dimensions depending on what you run it on.

4. **r* is not even monotone in the true dimension.** Sweeping k at fixed width,
   r* rises and then falls, because a k-dimensional function of a 64-dimensional
   input stops being special as k approaches d. Which direction it moves depends
   on how the link's roughness is normalised as k grows - a choice the paper never
   had to make, and which sets the answer.

5. **r* is a ratio to a baseline.** It is defined relative to full training, so
   anything that weakens the baseline lowers the apparent intrinsic dimension.
   Here the fully trained model does not reach the Bayes ceiling, and r* read
   against the ceiling is larger than r* read against the baseline.

Numbers in this docstring are restated from the cached run and build() asserts
each of them.

Discipline
----------
Everything here is synthetic, generated by quantpost/models/scaffold.py. The
paper's published figures are quoted as published. No claim is made about any
company, product or institution.
"""

