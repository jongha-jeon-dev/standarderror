def _rows(sw):
    return sorted(sw["rows"], key=lambda r: r["rank"])


def _rec(sw, rank: int) -> float:
    return next(r["recovery"] for r in sw["rows"] if r["rank"] == rank)


def _acc(sw, rank: int) -> float:
    return next(r["acc"] for r in sw["rows"] if r["rank"] == rank)


def _abl(sw, rank: int) -> float:
    return next(r["acc_ablated"] for r in sw["rows"] if r["rank"] == rank)


def _rec_ceiling(sw, rank: int) -> float:
    """Recovery measured against the Bayes ceiling instead of against the
    baseline. Same numerator, honest denominator."""
    return (_acc(sw, rank) - 0.5) / (sw["bayes"] - 0.5)


def r_star(sw, *, target: float = TARGET, ceiling: bool = False):
    if not ceiling:
        return sf.minimum_rank(sw["rows"], target=target)
    rows = [{"rank": r["rank"], "recovery": _rec_ceiling(sw, r["rank"])}
            for r in sw["rows"]]
    return sf.minimum_rank(rows, target=target)


def md_table(header, rows) -> str:
    def cell(x):
        return str(x).replace("|", r"\|")
    out = ["| " + " | ".join(cell(h) for h in header) + " |",
           "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


