def _snippets(res: dict) -> dict:
    """Every code block in the post, executed at build time.

    The third block trains, which is why the post's build is not instant. It runs
    the same three conditions the figure averages, at seed 0, so the numbers it
    prints are one of the three runs behind the figure rather than a separate
    demonstration that happens to look similar.
    """
    s = Session()
    out = {}

    out["task"] = s.run(f"""
        import numpy as np, torch

        class MultiIndexTask:
            "A label that depends on x only through a k-dimensional subspace."

            def __init__(self, d=64, k=4, seed=0, freq=1.5, harmonics=6, temp=3.0):
                g = torch.Generator().manual_seed(seed)
                self.U, _ = torch.linalg.qr(torch.randn(d, k, generator=g))
                W = torch.randn(harmonics, k, generator=g)
                self.W = W / W.norm(dim=1, keepdim=True) * freq   # fixed roughness
                self.phase = torch.rand(harmonics, generator=g) * 2 * np.pi
                self.c, self.d, self.temp = torch.randn(harmonics, generator=g), d, temp
                raw = self._raw(torch.randn(20_000, d, generator=g) @ self.U)
                self.mu, self.sd = raw.mean(), raw.std()

            def _raw(self, z):
                return torch.cos(z @ self.W.T + self.phase) @ self.c

            def score(self, X):
                return (self._raw(X @ self.U) - self.mu) / self.sd * self.temp

            def sample(self, n, split=0):
                g = torch.Generator().manual_seed(1_000_003 * (split + 1))
                X = torch.randn(n, self.d, generator=g)
                p = torch.sigmoid(self.score(X))
                return X, (torch.rand(p.shape, generator=g) < p).long()

        task = MultiIndexTask(d={D_IN}, k={BASE_K}, seed={SEED}, freq={FREQ})
        X, y = task.sample(20_000, split=99)
        print("bayes accuracy", round(float((((task.score(X) > 0).long() == y)
                                             .float().mean())), 4))

        # The property that makes the whole experiment possible: move x anywhere
        # outside the subspace and the label's distribution does not notice.
        Q, _ = torch.linalg.qr(torch.cat([task.U, torch.randn({D_IN}, {D_IN - BASE_K})], 1))
        off = (Q[:, {BASE_K}:] @ torch.randn({D_IN - BASE_K}, 512)).T * 5.0
        shift = (task.score(X[:512] + off) - task.score(X[:512])).abs().max()
        print(f"score shift off-subspace {{float(shift):.1e}}")
    """, expect=["bayes accuracy 0.82"])

    out["layer"] = s.run(f"""
        import torch.nn as nn, torch.nn.functional as F

        class ScaffoldLinear(nn.Module):
            "beta * W_seed h + (alpha/r) B A h, with W_seed frozen forever."

            def __init__(self, d_in, d_out, rank, alpha=1.0, seed=0):
                super().__init__()
                g = torch.Generator().manual_seed(seed)
                self.register_buffer("W_seed",                     # a buffer, so no
                    torch.randn(d_out, d_in, generator=g)          # optimiser state
                    * np.sqrt(2.0 / d_in))                         # is ever made
                self.A = nn.Parameter(torch.randn(rank, d_in, generator=g)
                                      * np.sqrt(2.0 / d_in))
                self.B = nn.Parameter(torch.randn(d_out, rank, generator=g)
                                      * np.sqrt(rank) / alpha)
                self.beta, self.rank, self.alpha = nn.Parameter(torch.ones(())), rank, alpha

            def forward(self, h):
                return (F.linear(h, self.W_seed) * self.beta
                        + (self.alpha / self.rank) * F.linear(F.linear(h, self.A), self.B))

        w = {BASE_WIDTH}
        for r in (1, 2, 16):
            lin = ScaffoldLinear(w, w, r)
            trained = lin.A.numel() + lin.B.numel() + 1
            print(f"rank {{r:2d}}: {{trained:5d}} trained of {{w * w:6d}} frozen"
                  f"  ({{100 * trained / (w * w):4.1f}}%)")
    """, expect=["rank  2:   385 trained"])

    out["fits"] = s.run(f"""
        from quantpost.models import scaffold as sf

        task = sf.MultiIndexTask(d={D_IN}, k={BASE_K}, seed={SEED}, freq={FREQ})
        splits = sf.make_splits(task, {N_TRAIN})       # shared by all three fits
        hidden = ({BASE_WIDTH},) * {DEPTH}

        full = sf.fit_one(task, rank=0, hidden=hidden, full=True, splits=splits)
        kept = sf.fit_one(task, rank=2, hidden=hidden, scaffold="ablate",
                          splits=splits)               # trains with it, then deletes
        none = sf.fit_one(task, rank=2, hidden=hidden, scaffold="zero",
                          splits=splits)               # never had one

        print(f"full-weight training           {{full['acc']:.4f}}")
        print(f"rank 2, frozen backbone        {{kept['acc']:.4f}}"
              f"   beta {{np.median(kept['beta']):.2f}}")
        print(f"  ... backbone then deleted    {{kept['acc_ablated']:.4f}}")
        print(f"rank 2, no backbone at all     {{none['acc']:.4f}}")
    """, expect=["full-weight training           0.78"])

    def _curve(k):
        rows = sorted(res["ks"][str(k)]["rows"], key=lambda x: x["rank"])
        return "[" + ", ".join(f"({r['rank']}, {r['recovery']:.3f})"
                               for r in rows) + "]"

    curve = ("{" + ", ".join(f"{k}: {_curve(k)}"
                             for k in sorted(int(x) for x in res["ks"])) + "}")
    out["rstar"] = s.run(f"""
        # (rank, recovery) for each task, recovery being the share of the fully
        # trained model's above-chance accuracy that the adapter reaches.
        curves = {curve}

        def minimum_rank(curve, target=0.99):
            "The paper's r*: the smallest rank on the grid that reaches target."
            for rank, rec in sorted(curve):
                if rec >= target:
                    return rank
            return None                  # 'did not saturate', not 'the last one'

        for k, curve in curves.items():
            print(f"true dimension k = {{k:>2d}}   r* = {{minimum_rank(curve)}}")
    """, expect=["true dimension k = 16   r* ="])

    return out


