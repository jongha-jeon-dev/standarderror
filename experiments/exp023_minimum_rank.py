def _fmt_star(v) -> str:
    return "never saturates" if v is None else str(v)


def _span(values) -> str:
    """A range that says so when part of it is 'no rank on the grid worked'."""
    named = sorted({v for v in values if v is not None})
    miss = any(v is None for v in values)
    if not named:
        return "never saturates"
    core = f"{named[0]}" if len(named) == 1 else f"{named[0]} to {named[-1]}"
    return core + (", or never saturates" if miss else "")


def _summary_rows(res: dict, prot: dict):
    ks = sorted(int(k) for k in res["ks"])
    ws = sorted(int(w) for w in res["widths"])
    at_n = [row for row in prot["rows"] if row["n_train"] == N_TRAIN]
    small = min(row["n_train"] for row in prot["rows"])
    lrs = sorted({row["lr"] for row in prot["rows"]})
    return [
        ["the task's true dimension", f"k = {min(ks)} to {max(ks)}",
         _span([r_star(res["ks"][str(k)]) for k in ks])],
        ["the backbone's width", f"{min(ws)} to {max(ws)} units",
         _span([r_star(res["widths"][str(w)]) for w in ws])],
        ["the learning rate",
         f"{min(r['lr'] for r in at_n):.0e} to {max(r['lr'] for r in at_n):.0e}, "
         f"at {N_TRAIN:,} rows",
         _span([row["r_star"] for row in at_n])],
        ["the training set size", f"{small:,} to {N_TRAIN:,} rows, "
         f"at lr {min(lrs):.0e}",
         _span([row["r_star"] for row in prot["rows"]
                if row["lr"] == min(lrs)])],
    ]


